"""The real slicer: list presets and slice the fixture tube (skipped, typed, without one)."""

from __future__ import annotations

from pathlib import Path

import pytest
from fastmcp import Client
from fastmcp.exceptions import ToolError

from slicer_mcp.backends.locate import locate
from slicer_mcp.errors import SlicerError
from slicer_mcp.server import mcp

from .conftest import MODEL


def _installed() -> str:
    try:
        return locate().describe()
    except SlicerError as exc:
        return f"skip: {exc.reason}"


INSTALLED = _installed()
pytestmark = [
    pytest.mark.slicer,
    pytest.mark.skipif(INSTALLED.startswith("skip"), reason=f"no slicer here ({INSTALLED})"),
]


async def test_slice_the_tube_and_list_presets(home: Path) -> None:
    async with Client(mcp) as client:
        printers = await client.call_tool("list_printers", {"printer": "Prusa MK4"})
        sliced = await client.call_tool(
            "slice",
            {
                "model": str(MODEL),
                "printer": "Prusa MK4",
                "material": "PLA",
                "quality": "0.2 mm",
                "overrides": {"perimeters": 3},
                "rotate": {"z": 45},
            },
        )
        with pytest.raises(ToolError) as unknown:
            await client.call_tool(
                "slice", {"model": str(MODEL), "printer": "Prusa MK4", "overrides": {"walls": 3}}
            )
        with pytest.raises(ToolError) as missing:
            await client.call_tool("slice", {"model": "/nowhere/part.stl", "printer": "Prusa MK4"})
    assert "0.20mm QUALITY @MK4 0.4" in printers.content[0].text
    data = sliced.structured_content
    assert data["printer"] == "Original Prusa MK4 0.4 nozzle"
    assert data["layer_count"] == 15
    assert data["estimates"]["print_time_s"] > 60
    assert data["overrides"] == ["perimeters = 3"]
    assert "binary_gcode = 0" in (Path(data["gcode"]).parent / "settings.ini").read_text()
    assert Path(data["gcode"]).read_text(errors="replace").startswith("; generated by PrusaSlicer")
    assert (home / "datadir" / "prusaslicer").is_dir()
    assert "[override_unknown]" in str(unknown.value)
    assert "[model_not_found]" in str(missing.value)
